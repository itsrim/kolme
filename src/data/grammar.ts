export function caseById(id: CaseId): CaseInfo {
  const found = CASES.find((item) => item.id === id);
  if (!found) throw new Error(id);
  return found;
}

export function nounById(id: string | undefined): Noun | undefined {
  return NOUNS.find((noun) => noun.id === id);
}
